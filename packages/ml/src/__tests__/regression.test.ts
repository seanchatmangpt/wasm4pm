describe('regressRemainingTime — Rank 3: metamorphic relations', () => {
  it('deterministic: same input produces identical R², slope, intercept', async () => {
    const data = makeNoisyLinear(20);
    const r1 = await regressRemainingTime(data, { method: 'linear_regression' });
    const r2 = await regressRemainingTime(data, { method: 'linear_regression' });
    expect(r1.rSquared).toBe(r2.rSquared);
    expect(r1.slope).toBe(r2.slope);
    expect(r1.intercept).toBe(r2.intercept);
    expect(r1.rmse).toBe(r2.rmse);
    expect(r1.mae).toBe(r2.mae);
  });

  it('deterministic: same input produces identical predictions array', async () => {
    const data = makeNoisyLinear(15);
    const r1 = await regressRemainingTime(data);
    const r2 = await regressRemainingTime(data);
    expect(r1.predictions).toEqual(r2.predictions);
  });

  it('higher-degree polynomial fits linear data at least as well as linear (R² monotone)', async () => {
    // Metamorphic: poly(d=2) has strictly more capacity than poly(d=1) = linear.
    // For any dataset, a higher-degree polynomial can only increase or match R².
    const data = makeNoisyLinear(20);
    const d1 = await regressRemainingTime(data, { method: 'polynomial_regression', degree: 1 });
    const d2 = await regressRemainingTime(data, { method: 'polynomial_regression', degree: 2 });
    // d2 has more capacity → R² should be >= R²(d1) (within numerical tolerance)
    expect(d2.rSquared).toBeGreaterThanOrEqual(d1.rSquared - 1e-6);
  });

  it('adding more traces from the same linear distribution keeps R² close to 1', async () => {
    // Metamorphic: more observations from the exact linear model → R² does not decrease.
    const small = await regressRemainingTime(makePerfectLinear(5));
    const large = await regressRemainingTime(makePerfectLinear(20));
    // Both should be ~1.0 for perfect data; large sample should not be worse.
    expect(large.rSquared).toBeGreaterThanOrEqual(small.rSquared - 1e-6);
  });

  it('shifting trace_length by constant does not change R² or slope', async () => {
    // Metamorphic: R² and slope are invariant under translation of x (OLS theorem).
    // (slope does not change; intercept adjusts to compensate)
    const base = makePerfectLinear(12);
    const shifted = base.map((r) => ({ ...r, trace_length: (r.trace_length as number) + 100 }));
    const r1 = await regressRemainingTime(base, { method: 'linear_regression' });
    const r2 = await regressRemainingTime(shifted, { method: 'linear_regression' });
    expect(r2.rSquared).toBeCloseTo(r1.rSquared, 5);
    expect(r2.slope!).toBeCloseTo(r1.slope!, 5);
  });

  it('scaling remaining_time by constant scales slope proportionally', async () => {
    // Metamorphic: y* = 2y → slope* = 2*slope (linear homogeneity of OLS).
    const base = makePerfectLinear(12);
    const scaled = base.map((r) => ({
      ...r,
      remaining_time: (r.remaining_time as number) * 2,
    }));
    const r1 = await regressRemainingTime(base);
    const r2 = await regressRemainingTime(scaled);
    expect(r2.slope!).toBeCloseTo(r1.slope! * 2, 4);
  });

  it('scaling remaining_time by constant scales intercept proportionally', async () => {
    const base = makePerfectLinear(12);
    const scaled = base.map((r) => ({
      ...r,
      remaining_time: (r.remaining_time as number) * 3,
    }));
    const r1 = await regressRemainingTime(base);
    const r2 = await regressRemainingTime(scaled);
    expect(r2.intercept!).toBeCloseTo(r1.intercept! * 3, 4);
  });

  it('scaling remaining_time by constant preserves R² (R² is scale-invariant)', async () => {
    // R² = 1 - ssRes/ssTot. Both numerator and denominator scale by k², so R² is invariant.
    const base = makeNoisyLinear(15);
    const scaled = base.map((r) => ({
      ...r,
      remaining_time: (r.remaining_time as number) * 5,
    }));
    const r1 = await regressRemainingTime(base);
    const r2 = await regressRemainingTime(scaled);
    expect(r2.rSquared).toBeCloseTo(r1.rSquared, 5);
  });

  it('adding a perfect outlier only mildly reduces R² on large datasets', async () => {
    // Metamorphic: on 20 good points + 1 outlier, R² should still be > 0.7 for strong signal.
    const base = makePerfectLinear(20);
    const withOutlier = [
      ...base,
      { case_id: 'outlier', trace_length: 10, remaining_time: 99999 },
    ];
    const r1 = await regressRemainingTime(base);
    const r2 = await regressRemainingTime(withOutlier);
    // With one outlier in 21 points, R² should be lower but model direction preserved.
    expect(r1.rSquared).toBeGreaterThan(r2.rSquared - 0.01); // r1 >= r2 (outlier hurts fit)
    expect(r2.slope!).toBeLessThan(0); // Direction still negative
  });
});
